async function updateExercises() {
  try {
    console.log('🔄 Обновляем упражнения в базе данных...');
    
    for (const [exerciseId, content] of Object.entries(exerciseContent)) {
      console.log(`\n📝 Обновляем упражнение #${exerciseId}...`);
      
      const { error } = await supabase
        .from('exercises')
        .update({
          instructions_ru: content.instructions,
          tips_ru: content.tips,
          updated_at: new Date().toISOString()
        })
        .eq('exercise_id', exerciseId);
      
      if (error) {
        console.error(`❌ Ошибка обновления упражнения #${exerciseId}:`, error);
      } else {
        console.log(`✅ Упражнение #${exerciseId} успешно обновлено`);
      }
    }
    
    console.log('\n🎉 Все упражнения обновлены!');
    
  } catch (error) {
    console.error('❌ Ошибка обновления:', error);
  }
}

// Запускаем обновление
updateExercises();








